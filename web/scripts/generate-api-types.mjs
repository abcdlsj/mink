const exportedSchema = spawnSync(
  "cargo",
  ["run", "--quiet", "--", "schema", "browser-openapi"],
  { cwd: repositoryRoot, encoding: "utf8" },
);
if (exportedSchema.status !== 0) {
  process.stderr.write(exportedSchema.stderr);
  process.exit(exportedSchema.status ?? 1);
}

const document = JSON.parse(exportedSchema.stdout);
const schemas = document.components?.schemas ?? {};
for (const schemaName of Object.values(exportedTypes)) {
  if (!(schemaName in schemas)) {
    throw new Error(`Rust OpenAPI schema is missing ${schemaName}`);
  }
}

const generated = astToString(await openapiTS(document));
const aliases = Object.entries(exportedTypes)
  .map(([typeName, schemaName]) =>
    `export type ${typeName} = components["schemas"]["${schemaName}"];`,
  )
  .join("\n");
const contents = `// This file is generated by \`mise run generate-api-types\`. Do not edit.\n${generated}\n${aliases}\n`;

if (check) {
  if (readFileSync(outputPath, "utf8") !== contents) {
    process.stderr.write("web/src/api/types.ts is stale; run `mise run generate-api-types`.\n");
    process.exit(1);
  }
} else {
  writeFileSync(outputPath, contents);
}
